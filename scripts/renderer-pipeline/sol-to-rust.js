#!/usr/bin/env node
// Converts the generated Solidity renderer leaves (contracts/Renderers,
// contracts/RenderersV2, ShatteredHiveMedalArt) into Rust data for the NEAR
// renderer contract (near/contracts/void-renderer/src/art.rs).
//
// Each leaf's render() is a fixed sequence of path-data literals (PART_n /
// SVG_BASE64 / a literal return) and colors (COLOR_n, blended with the ship's
// hue via blendHSL / blendHSLV2 when shiny). The output order equals the
// source order of those expressions; this script asserts the shapes it
// relies on, and the golden parity test proves the output byte-identical.
//
//   node scripts/renderer-pipeline/sol-to-rust.js
//
// Written 2026-11-13.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "../..");
const OUT = path.join(ROOT, "near/contracts/void-renderer/src/art.rs");

// Leaves per variant, by role (the deploy module's dispatcher wiring).
const LEAVES = {
  v1: {
    dir: "contracts/Renderers",
    suffix: "",
    explosion: ["RenderExplosion1", "RenderExplosion2"],
    unconstructed: ["RenderUnconstructed1", "RenderUnconstructed2"],
  },
  v2: {
    dir: "contracts/RenderersV2",
    suffix: "V2",
    explosion: ["RenderExplosion1V2", "RenderExplosion2V2", "RenderExplosion3V2"],
    unconstructed: [1, 2, 3, 4, 5].map((n) => `RenderUnconstructed${n}V2`),
  },
};
const ROLES = [
  "Special1", "Special2", "Special3",
  "Aft0", "Aft1", "Aft2",
  "Weapon1", "Weapon2", "Weapon3", "Weapon4",
  "Fore0", "Fore1", "Fore2", "ForePerfect",
  "BaseBody", "Shield1", "Shield2", "Shield3", "Armor1", "Armor2", "Armor3",
];

function fail(msg) {
  throw new Error(msg);
}

// string constants: NAME = '...'; or "..." (possibly on the next line)
function constants(src) {
  const out = {};
  const re = /constant\s+([A-Z0-9_]+)\s*=\s*(['"])([\s\S]*?)\2\s*;/g;
  let m;
  while ((m = re.exec(src))) {
    if (m[3].includes("\\")) fail(`escape sequence in ${m[1]}`);
    out[m[1]] = m[3];
  }
  return out;
}

function renderBody(src, file) {
  const i = src.indexOf("function render(");
  if (i < 0) fail(`${file}: no render()`);
  return src.slice(i);
}

// Ordered segments of one leaf.
function leafSegments(file) {
  const src = fs.readFileSync(path.join(ROOT, file), "utf-8");
  const consts = constants(src);
  let body = renderBody(src, file);

  if (/return\s+SVG_BASE64\s*;/.test(body)) {
    if (!("SVG_BASE64" in consts)) fail(`${file}: SVG_BASE64 missing`);
    return [{ lit: consts.SVG_BASE64 }];
  }

  // V1 shape: chunkN declarations combined by `return string.concat(chunk1..)`
  const ret = body.match(/return\s+string\.concat\(([^)]*)\)\s*;/);
  if (ret) {
    const chunks = ret[1].split(",").map((s) => s.trim());
    chunks.forEach((c, k) => {
      if (c !== `chunk${k + 1}`) fail(`${file}: chunks not combined in order (${ret[1]})`);
    });
  } else if (!/return\s+result\s*;/.test(body)) {
    fail(`${file}: unknown render() shape`);
  }

  // Replace each shiny ternary with a single COLOR token, then scan tokens.
  const ternary =
    /ship\.shipData\.shiny\s*\?\s*(blendHSL|blendHSLV2)\(\s*ship\.traits\.colors\.h1\s*,\s*ship\.traits\.colors\.s1\s*,\s*ship\.traits\.colors\.l1\s*,\s*(COLOR_\d+)\s*\)\s*:\s*(COLOR_\d+)/g;
  body = body.replace(ternary, (_, fn, c1, c2) => {
    if (c1 !== c2) fail(`${file}: mismatched ternary ${c1}/${c2}`);
    return ` @${fn}:${c1} `;
  });
  if (/COLOR_\d+(?![\d])/.test(body.replace(/@blendHSL(V2)?:COLOR_\d+/g, ""))) {
    fail(`${file}: COLOR used outside the shiny-blend pattern`);
  }
  const segs = [];
  const tok = /@(blendHSL|blendHSLV2):(COLOR_\d+)|\b(PART_\d+)\b/g;
  let m;
  while ((m = tok.exec(body))) {
    if (m[3]) {
      if (!(m[3] in consts)) fail(`${file}: ${m[3]} missing`);
      segs.push({ lit: consts[m[3]] });
    } else {
      if (!(m[2] in consts)) fail(`${file}: ${m[2]} missing`);
      segs.push({ color: consts[m[2]], blend: m[1] === "blendHSLV2" ? "V2" : "V1" });
    }
  }
  if (segs.length === 0) fail(`${file}: no segments`);
  return segs;
}

function rustStr(s) {
  // Raw string with enough #s to be safe.
  let hashes = "#";
  while (s.includes(`"${hashes}`)) hashes += "#";
  return `r${hashes}"${s}"${hashes}`;
}

function emitSegs(name, segs) {
  const items = segs.map((s) =>
    s.lit !== undefined ? `    Seg::Lit(${rustStr(s.lit)}),` : `    Seg::Color(${rustStr(s.color)}, Blend::${s.blend}),`,
  );
  return `pub static ${name}: &[Seg] = &[\n${items.join("\n")}\n];\n`;
}

function main() {
  let out = `// @generated by scripts/renderer-pipeline/sol-to-rust.js from the Solidity
// renderer leaves. Do not edit by hand; regenerate after the art changes.

use crate::render::{Blend, Seg};

`;
  const tables = {};
  for (const [v, cfg] of Object.entries(LEAVES)) {
    tables[v] = {};
    for (const role of ROLES) {
      const contract = `Render${role}${cfg.suffix}`;
      const name = `${v.toUpperCase()}_${role.toUpperCase()}`;
      out += emitSegs(name, leafSegments(`${cfg.dir}/${contract}.sol`));
      tables[v][role] = name;
    }
    for (const kind of ["explosion", "unconstructed"]) {
      const names = cfg[kind].map((c, i) => {
        const name = `${v.toUpperCase()}_${kind.toUpperCase()}_${i + 1}`;
        out += emitSegs(name, leafSegments(`${cfg.dir}/${c}.sol`));
        return name;
      });
      out += `pub static ${v.toUpperCase()}_${kind.toUpperCase()}: &[&[Seg]] = &[${names.join(", ")}];\n`;
    }
  }
  // Medal art: a single literal SVG.
  const medal = fs.readFileSync(path.join(ROOT, "contracts/ShatteredHiveMedalArt.sol"), "utf-8");
  const mm = medal.match(/return\s+'([^']*)'\s*;/);
  if (!mm) fail("ShatteredHiveMedalArt: unexpected shape");
  out += `pub static MEDAL_SVG: &str = ${rustStr(mm[1])};\n`;

  // Per-variant leaf tables in dispatcher order.
  out += "\npub struct VariantArt {\n";
  for (const role of ROLES) out += `    pub ${role.toLowerCase()}: &'static [Seg],\n`;
  out += "    pub explosion: &'static [&'static [Seg]],\n    pub unconstructed: &'static [&'static [Seg]],\n}\n\n";
  for (const v of Object.keys(LEAVES)) {
    out += `pub static ${v.toUpperCase()}: VariantArt = VariantArt {\n`;
    for (const role of ROLES) out += `    ${role.toLowerCase()}: ${tables[v][role]},\n`;
    out += `    explosion: ${v.toUpperCase()}_EXPLOSION,\n    unconstructed: ${v.toUpperCase()}_UNCONSTRUCTED,\n};\n`;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${(out.length / 1024).toFixed(0)} KB)`);
}

main();
