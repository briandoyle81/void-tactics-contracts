const fs = require("fs");
const path = require("path");

// Splits one standalone SVG (e.g. an image-to-svg.js output) into on-chain
// leaf contracts, for static art too big for a single contract (24KB cap,
// CLAUDE.md -- never bypassed). Added 2026-10-16 for the per-variant
// destroyed (explosion) and unconstructed images.
//
// The leaves hold the whole SVG already BASE64-ENCODED, cut into pieces of
// at most --budget characters. ImageRenderer* joins them in order behind
// "data:image/svg+xml;base64,". Encoding off-chain matters: OpenZeppelin's
// Base64 costs ~78 gas per byte, and on-chain encoding of a 237KB image
// pushed one tokenURI read to ~86M gas -- past common eth_call caps.
// Any cut point works, since the pieces are only ever concatenated.
//
// Usage:
//   node scripts/renderer-pipeline/svg-to-leaves.js <in.svg> <outDir> <namePattern> [--budget=CHARS]
// namePattern contains "{n}", replaced by the 1-based leaf index, e.g.
// "RenderExplosion{n}" or "RenderExplosion{n}V2".

const DEFAULT_BUDGET = 23000;

function splitSvg(svg, budget) {
  const open = svg.match(/^\s*(<svg[^>]*>)/);
  const paths = svg.match(/<path[^>]*\/>/g) || [];
  if (!open || paths.length === 0) throw new Error("expected an <svg> of <path/> elements");
  // Inline CSS fill -> attribute (shorter, same rendering).
  const compact = paths.map((p) => p.replace(/ style="fill:(#[0-9a-fA-F]{3,8});?"/, ' fill="$1"'));
  const b64 = Buffer.from(open[1] + compact.join("") + "</svg>", "utf8").toString("base64");

  const chunks = [];
  for (let i = 0; i < b64.length; i += budget) chunks.push(b64.slice(i, i + budget));
  return chunks;
}

function leafSource(name, chunk, srcName) {
  return (
    `// SPDX-License-Identifier: UNLICENSED\n` +
    `pragma solidity ^0.8.28;\n\n` +
    `import "../Types.sol";\n` +
    `import "../IRenderer.sol";\n\n` +
    `// Generated by scripts/renderer-pipeline/svg-to-leaves.js from ${srcName}.\n` +
    `// Holds base64-encoded SVG, not raw SVG markup (see the script).\n` +
    `contract ${name} is IReturnSVG {\n` +
    `    string private constant SVG_BASE64 =\n` +
    `        '${chunk}';\n\n` +
    `    function render(Ship memory) external pure override returns (string memory) {\n` +
    `        return SVG_BASE64;\n` +
    `    }\n` +
    `}\n`
  );
}

function main() {
  const args = process.argv.slice(2);
  const flags = Object.fromEntries(
    args.filter((a) => a.startsWith("--")).map((a) => a.slice(2).split("=")),
  );
  const [inPath, outDir, pattern] = args.filter((a) => !a.startsWith("--"));
  if (!inPath || !outDir || !pattern || !pattern.includes("{n}")) {
    console.error(
      "Usage: node svg-to-leaves.js <in.svg> <outDir> <namePattern with {n}> [--budget=CHARS]",
    );
    process.exit(1);
  }
  const budget = flags.budget ? Number(flags.budget) : DEFAULT_BUDGET;

  const chunks = splitSvg(fs.readFileSync(inPath, "utf8"), budget);
  fs.mkdirSync(outDir, { recursive: true });
  chunks.forEach((chunk, i) => {
    const name = pattern.replace("{n}", String(i + 1));
    const outPath = path.join(outDir, `${name}.sol`);
    fs.writeFileSync(outPath, leafSource(name, chunk, path.basename(inPath)));
    console.log(`[svg-to-leaves] wrote ${outPath} (${chunk.length} base64 chars)`);
  });
}

if (require.main === module) main();

module.exports = { splitSvg };
