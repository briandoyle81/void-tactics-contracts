// Generates near/crates/vt-core/src/ship_names_data.rs from
// near/seed/ship_names.json: the exact name subsets held by the deployed
// OnchainShipNames contract (Base Sepolia 0x2b6C2e73D7D8B9dd49aF848B7A19FF003ED0d779),
// in its constructor order. Source repo: github.com/briandoyle81/onchain_names.
// Names: Unlicense / public domain (smashew/NameDatabases).
//
//   node scripts/near-golden/genShipNames.js
//
// Written 2026-11-13. CI checks the output is up to date.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "../..");
const src = JSON.parse(fs.readFileSync(path.join(root, "near/seed/ship_names.json"), "utf8"));
const lit = (s) => JSON.stringify(s); // names contain no characters JSON and Rust escape differently
for (const sub of src.subsets) for (const n of sub) if (/[\\"\u0000-\u001f]/.test(n)) throw new Error(`unsupported character in ${lit(n)}`);

let out = "// @generated by scripts/near-golden/genShipNames.js from near/seed/ship_names.json. Do not edit.\n";
out += "// Names: Unlicense / public domain (https://github.com/smashew/NameDatabases/blob/master/LICENSE).\n\n";
out += `pub static SUBSETS: [&[&str]; ${src.subsets.length}] = [\n`;
for (const sub of src.subsets) out += `    &[${sub.map(lit).join(", ")}],\n`;
out += "];\n";
fs.writeFileSync(path.join(root, "near/crates/vt-core/src/ship_names_data.rs"), out);
console.log(`wrote ${src.subsets.length} subsets, ${src.subsets.reduce((a, s) => a + s.length, 0)} names`);
